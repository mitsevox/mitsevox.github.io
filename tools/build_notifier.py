#!/usr/bin/env python3
"""Build the reusable notifier and prepare pinned producer caller workflows."""
import argparse
import json
from pathlib import Path
from reporting.github import GitHub
from reporting.registry import producer, site_config
from reporting.validation import ROOT, SHA, require


def reusable(root=ROOT):
    code=(Path(root)/'tools/notify_report.py').read_text()
    prefix='''# Generated by tools/build_notifier.py; validator source is tools/notify_report.py.
name: Notify shared portfolio
on:
  workflow_call:
    inputs:
      project:
        type: string
        required: true
      producer_branch:
        type: string
        default: main
      producer_workflow:
        type: string
        required: true
      site_repository:
        type: string
        required: true
      app_client_id:
        type: string
        required: true
    secrets:
      app_private_key:
        required: true
permissions:
  contents: read
jobs:
  notify:
    runs-on: ubuntu-24.04
    timeout-minutes: 5
    steps:
      - name: Validate completed main report event
        id: notification
        env:
          PROJECT: ${{ inputs.project }}
          PRODUCER_BRANCH: ${{ inputs.producer_branch }}
          PRODUCER_WORKFLOW: ${{ inputs.producer_workflow }}
          SITE_REPOSITORY: ${{ inputs.site_repository }}
        run: |
          python3 - <<'PY'
'''
    suffix='''          PY
      - name: Create site-scoped notification token
        id: app
        uses: actions/create-github-app-token@64ab729a6294000f5aa4a4bc0b73d1f32bc45510 # v3.3.0
        with:
          client-id: ${{ inputs.app_client_id }}
          private-key: ${{ secrets.app_private_key }}
          owner: ${{ steps.notification.outputs.site_owner }}
          repositories: ${{ steps.notification.outputs.site_name }}
          permission-contents: write
      - name: Request authenticated report refresh
        env:
          GH_TOKEN: ${{ steps.app.outputs.token }}
          SITE_REPOSITORY: ${{ inputs.site_repository }}
        run: gh api --method POST "repos/$SITE_REPOSITORY/dispatches" --input "$RUNNER_TEMP/report-notification.json"
'''
    return prefix+''.join('          '+line+'\n' if line else '\n' for line in code.splitlines())+suffix


def caller(root,slug,revision,workflow_name):
    require(SHA.fullmatch(revision),'Pin a full approved site automation commit')
    policy=producer(root,slug)
    values={'workflow':policy['workflow'],'branch':policy['branch'],'name':workflow_name}
    j=json.dumps
    return f'''# No producer code or report artifact is executed by this completion notifier.
name: Notify portfolio
on:
  workflow_run:
    workflows: [{j(values['name'])}]
    types: [completed]
    branches: [{j(values['branch'])}]
permissions:
  contents: read
jobs:
  notify:
    if: >-
      github.event.workflow_run.conclusion == 'success' &&
      (github.event.workflow_run.event == 'push' || github.event.workflow_run.event == 'workflow_dispatch') &&
      github.event.workflow_run.head_branch == {"'"+values['branch'].replace("'","''")+"'"} &&
      github.event.workflow_run.head_repository.full_name == github.repository &&
      github.event.workflow_run.path == {"'"+values['workflow']+"'"}
    uses: {site_config(root)['repository']}/.github/workflows/notify-site.yml@{revision}
    with:
      project: {slug}
      producer_branch: {j(values['branch'])}
      producer_workflow: {j(values['workflow'])}
      site_repository: {j(site_config(root)['repository'])}
      app_client_id: ${{{{ vars.PORTFOLIO_APP_CLIENT_ID }}}}
    secrets:
      app_private_key: ${{{{ secrets.PORTFOLIO_APP_PRIVATE_KEY }}}}
'''


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--project')
    parser.add_argument('--site-revision')
    parser.add_argument('--output',type=Path)
    args=parser.parse_args()
    if args.project:
        require(args.output is not None and args.site_revision,'Select output and approved site revision')
        policy=producer(ROOT,args.project)
        name=GitHub(policy['repository']).get('actions/workflows/'+policy['workflow'].rsplit('/',1)[1])['name']
        args.output.parent.mkdir(parents=True,exist_ok=True)
        args.output.write_text(caller(ROOT,args.project,args.site_revision,name))
    else:
        (ROOT/'.github/workflows/notify-site.yml').write_text(reusable())
